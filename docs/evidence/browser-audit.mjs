// Auditoría reproducible. Dependencias auxiliares fuera del proyecto, en TEMP.
// Ejecutar con node docs/evidence/browser-audit.mjs con Vite en 127.0.0.1:5173.
import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { pathToFileURL, fileURLToPath } from 'node:url';
const require = createRequire(path.join(os.tmpdir(), 'horarios-maker-audit-deps', 'package.json'));
const { chromium } = require('playwright');
const { PNG } = require('pngjs');
const pixelmatch = (await import(pathToFileURL(path.join(os.tmpdir(), 'horarios-maker-audit-deps/node_modules/pixelmatch/index.js')).href)).default;
const out = path.dirname(fileURLToPath(import.meta.url));
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.AUDIT_BROWSER_PATH ? { executablePath: process.env.AUDIT_BROWSER_PATH } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 2, acceptDownloads: true });
const page = await context.newPage();
const findings = [];
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const add = (id, result) => findings.push({ id, ...result });
await page.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' });
await page.evaluate(() => document.fonts.ready);
const original = await page.evaluate(() => localStorage.getItem('horario-app-state'));
await page.screenshot({ path: path.join(out, '01-empty-desktop.png') });
add('initial', await page.evaluate(() => ({ title: document.title, fonts: [...document.fonts].map(f => ({ family: f.family, status: f.status })), switches: [...document.querySelectorAll('[role=switch]')].map(e => ({ text: e.textContent, ariaLabel: e.getAttribute('aria-label'), labelledBy: e.getAttribute('aria-labelledby') })) })));
await page.getByRole('button', { name: 'Agregar', exact: true }).click();
await page.getByRole('button', { name: /Nueva materia Lun/ }).click();
await page.getByLabel('Materia', { exact: true }).fill('Análisis matemático');
await page.getByLabel('Aula', { exact: true }).fill('305');
await page.getByLabel('Detalle', { exact: true }).fill('Teoría');
await page.getByRole('button', { name: 'Agregar', exact: true }).click();
add('overlap', await page.evaluate(() => ({ items: JSON.parse(localStorage.getItem('horario-app-state')).items, rects: [...document.querySelectorAll('.canvas-frame svg > g > rect')].map(e => ({ x: e.getAttribute('x'), y: e.getAttribute('y'), width: e.getAttribute('width'), height: e.getAttribute('height') })) })));
await page.screenshot({ path: path.join(out, '02-overlap.png') });
const beforeDelete = await page.evaluate(() => localStorage.getItem('horario-app-state'));
await page.evaluate(() => { document.activeElement?.blur(); });
await page.locator('.canvas-frame svg').click();
await page.keyboard.press('Delete');
const afterDelete = await page.evaluate(() => localStorage.getItem('horario-app-state'));
await page.keyboard.press('Control+z');
const afterUndo = await page.evaluate(() => localStorage.getItem('horario-app-state'));
add('canvas-keyboard', { before: JSON.parse(beforeDelete).items, afterDelete: JSON.parse(afterDelete).items, afterUndo: JSON.parse(afterUndo).items, activeElement: await page.evaluate(() => document.activeElement.tagName) });
await page.getByRole('button', { name: 'Nueva materia Lun', exact: false }).click();
await page.locator('input[id^=subject-]').last().fill('');
add('clear-name', { value: await page.locator('input[id^=subject-]').last().inputValue() });
await page.locator('input[id^=start-]').last().fill('23:59');
add('late-time', { start: await page.locator('input[id^=start-]').last().inputValue(), end: await page.locator('input[id^=end-]').last().inputValue() });
// Restaurar fixture válido por recarga en contexto aislado, sin datos del usuario.
await page.evaluate(s => localStorage.setItem('horario-app-state', s), beforeDelete);
await page.reload({ waitUntil: 'networkidle' });
await page.evaluate(() => document.fonts.ready);
const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Descargar', exact: true }).click()]);
await download.saveAs(path.join(out, '03-export-original.png'));
const exported = PNG.sync.read(await fs.readFile(path.join(out, '03-export-original.png')));
add('export', { width: exported.width, height: exported.height });
const markup = await page.locator('.canvas-frame svg').evaluate(e => new XMLSerializer().serializeToString(e));
await fs.writeFile(path.join(out, '03-serialized-current.svg'), markup);
add('font-payload', { hasFontFace: markup.includes('@font-face'), hasEmbeddedFont: markup.includes('data:font'), referencesBebas: markup.includes('Bebas Neue') });
await page.locator('.canvas-frame svg').evaluate(e => { e.style.cssText = 'width:1000px;height:1414px;max-width:none;max-height:none;border-radius:0;box-shadow:none;'; document.querySelector('.canvas-area').style.overflow = 'visible'; document.querySelector('.canvas-frame').style.cssText = 'display:block;width:1000px;height:1414px;flex-shrink:0;'; });
await page.setViewportSize({ width: 1600, height: 1650 });
await page.locator('.canvas-frame svg').screenshot({ path: path.join(out, '03-live-svg.png') });
const live = PNG.sync.read(await fs.readFile(path.join(out, '03-live-svg.png')));
if (live.width === exported.width && live.height === exported.height) {
  const diff = new PNG({ width: live.width, height: live.height });
  const pixels = pixelmatch(live.data, exported.data, diff.data, live.width, live.height, { threshold: 0.1 });
  await fs.writeFile(path.join(out, '03-diff.png'), PNG.sync.write(diff));
  add('raster-diff', { pixels, total: live.width * live.height, fraction: pixels / (live.width * live.height), note: 'Captura DOM SVG vs PNG descargado, misma geometría 2x; incluye diferencia de rasterización y tipografía.' });
} else add('raster-diff', { skipped: true, live: [live.width, live.height], exported: [exported.width, exported.height] });
await page.evaluate(s => localStorage.setItem('horario-app-state', s), beforeDelete);
await page.setViewportSize({ width: 390, height: 844 });
await page.reload({ waitUntil: 'networkidle' });
await page.screenshot({ path: path.join(out, '04-mobile.png') });
add('mobile', await page.evaluate(() => ({ viewport: [innerWidth, innerHeight], documentWidth: document.documentElement.scrollWidth, bodyOverflow: getComputedStyle(document.body).overflow, buttons: [...document.querySelectorAll('.toolbar button')].map(b => ({ name: b.textContent || b.getAttribute('aria-label'), rect: b.getBoundingClientRect().toJSON() })), canvas: document.querySelector('.canvas-area').getBoundingClientRect().toJSON(), svg: document.querySelector('.canvas-frame svg').getBoundingClientRect().toJSON() })));
await page.setViewportSize({ width: 320, height: 568 });
await page.screenshot({ path: path.join(out, '04-mobile-320.png') });
add('mobile-320', await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth, toolbarLeft: document.querySelector('.toolbar-actions').getBoundingClientRect().left, toolbarRight: document.querySelector('.toolbar-actions').getBoundingClientRect().right, canvasBottom: document.querySelector('.canvas-area').getBoundingClientRect().bottom, viewportHeight: innerHeight })));
await page.setViewportSize({ width: 1440, height: 1000 });
const [jsonDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Exportar JSON', exact: true }).click()]);
await jsonDownload.saveAs(path.join(out, '06-roundtrip.json'));
const jsonBytes = await fs.readFile(path.join(out, '06-roundtrip.json'));
const exportedState = JSON.parse(jsonBytes.toString());
await page.locator('input[type=file]').setInputFiles({ name: 'roundtrip.json', mimeType: 'application/json', buffer: jsonBytes });
add('json-roundtrip', { equal: JSON.stringify(exportedState) === await page.evaluate(() => localStorage.getItem('horario-app-state')) });
await page.getByRole('button', { name: /Análisis matemático Lun/ }).click();
await page.getByRole('button', { name: 'Eliminar', exact: true }).click();
add('delete-block', await page.evaluate(() => ({ items: JSON.parse(localStorage.getItem('horario-app-state')).items.length })));
await page.locator('input[type=file]').setInputFiles({ name: 'empty-object.json', mimeType: 'application/json', buffer: Buffer.from('{}') });
add('empty-object-import', await page.evaluate(() => ({ items: JSON.parse(localStorage.getItem('horario-app-state')).items.length, status: document.querySelector('.toolbar-status').textContent })));
await page.evaluate(s => localStorage.setItem('horario-app-state', s), beforeDelete);
await page.reload({ waitUntil: 'networkidle' });
await page.getByRole('textbox', { name: 'Título', exact: true }).fill('Horario para cursada de ingeniería y ciencias con un título demasiado largo para el documento');
add('long-title', await page.locator('.canvas-frame svg').evaluate(svg => { const box = svg.querySelector('text').getBBox(); return { title: { x: box.x, y: box.y, width: box.width, height: box.height }, viewBox: svg.viewBox.baseVal.width }; }));
await page.screenshot({ path: path.join(out, '07-long-title.png') });
const outside = JSON.parse(beforeDelete);
outside.settings.timeRangeMode = 'manual'; outside.settings.documentStartHour = 8; outside.settings.documentEndHour = 9;
outside.items = [{ ...outside.items[0], start: '10:00', end: '11:00' }];
await page.locator('input[type=file]').setInputFiles({ name: 'outside.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(outside)) });
await page.screenshot({ path: path.join(out, '08-outside-range.png') });
add('outside-range', await page.locator('.canvas-frame svg').evaluate(svg => ({ rects: [...svg.querySelectorAll(':scope > rect, :scope > g > rect')].map(e => ({ x: e.getAttribute('x'), y: e.getAttribute('y'), height: e.getAttribute('height') })) })));
await page.evaluate(s => localStorage.setItem('horario-app-state', s), beforeDelete);
await page.reload({ waitUntil: 'networkidle' });
// Reset elimina sin confirmación ni recuperación.
await page.setViewportSize({ width: 1440, height: 1000 });
await page.getByRole('button', { name: 'Reiniciar horario', exact: true }).click();
await page.keyboard.press('Control+z');
add('reset-undo', await page.evaluate(() => ({ items: JSON.parse(localStorage.getItem('horario-app-state')).items.length })));
// Enlace malformado no debería borrar el local válido.
await page.evaluate(s => localStorage.setItem('horario-app-state', s), beforeDelete);
await page.goto('http://127.0.0.1:5173/?s=invalid', { waitUntil: 'networkidle' });
add('bad-link', await page.evaluate(() => ({ items: JSON.parse(localStorage.getItem('horario-app-state')).items.length, status: document.querySelector('.toolbar-status').textContent, url: location.href })));
// Importación sintácticamente válida con enum inválido falla después de sanitize.
await page.locator('input[type=file]').setInputFiles({ name: 'bad-theme.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ version: 1, settings: { theme: 'inexistente' }, items: [] })) });
await page.waitForTimeout(400);
add('bad-import', { errors: [...errors], rootText: await page.locator('#root').innerText() });
await page.screenshot({ path: path.join(out, '05-crash-invalid-theme.png') });
// Probar almacenamiento que falla en otro contexto sin alterar la implementación.
const quotaPage = await context.newPage();
const quotaErrors = [];
quotaPage.on('pageerror', e => quotaErrors.push(e.message));
await quotaPage.addInitScript(() => { Storage.prototype.setItem = function () { throw new DOMException('Audit quota', 'QuotaExceededError'); }; });
await quotaPage.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' });
add('quota', { errors: quotaErrors, body: (await quotaPage.locator('body').innerText()).slice(0, 400) });
await fs.writeFile(path.join(out, 'browser-results.json'), JSON.stringify({ date: new Date().toISOString(), browser: browser.version(), isolatedContext: true, initialStorage: original, findings }, null, 2));
console.log(JSON.stringify(findings, null, 2));
await browser.close();
